// Writes src/maplibre-css.generated.ts from the stylesheet of the installed maplibre-gl, so the
// map can adopt it inside a shadow root without the host importing any CSS.
//   node scripts/sync-maplibre-css.mjs          update the file
//   node scripts/sync-maplibre-css.mjs --check  fail when the file is out of date (CI)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
const cssPath = join(
  dirname(require.resolve('maplibre-gl/package.json')),
  'dist',
  'maplibre-gl.css',
);
const target = join(root, 'src', 'maplibre-css.generated.ts');

/** Drops comments and layout whitespace: enough to keep the string small, safe for plain CSS. */
const minify = (css) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([{}:;,>])\s*/g, '$1')
    .replace(/;}/g, '}')
    .trim();

const { version } = JSON.parse(readFileSync(join(dirname(cssPath), '..', 'package.json'), 'utf8'));
const next = `// Generated by scripts/sync-maplibre-css.mjs from maplibre-gl ${version}. Do not edit.\nexport const maplibreCss: string = ${JSON.stringify(minify(readFileSync(cssPath, 'utf8')))};\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== next) {
    console.error(
      'src/maplibre-css.generated.ts is out of date. Run: node scripts/sync-maplibre-css.mjs',
    );
    process.exit(1);
  }
} else if (!existsSync(target) || readFileSync(target, 'utf8') !== next) {
  writeFileSync(target, next);
  console.log(`wrote src/maplibre-css.generated.ts (maplibre-gl ${version}, ${next.length} bytes)`);
}
